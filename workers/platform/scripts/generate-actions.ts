function renderActionDefinition(action: ActionSource): string {
  const constant = actionConstantPrefix(action);
  const definition = JSON.stringify(
    {
      provider: action.provider,
      verb: action.verb,
      method: action.method,
      pathPattern: action.path,
      stakes: action.stakes,
      argsSchema: buildJsonSchema(action),
      resourceKey: action.resourceKey,
      idempotency: action.idempotency,
      credentialScope: action.credentialScope,
      auditFields: action.auditFields,
    },
    null,
    2,
  );
  return (
    `export const ${constant}_TOOL = ${JSON.stringify(action.command)};\n\n` +
    `export const ${constant}_DEF = ${definition} as const satisfies ActionDef;`
  );
}

function actionConstantPrefix(action: ActionSource): string {
  return action.id.toUpperCase();
}


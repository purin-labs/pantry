function buildJsonSchema(action: ActionSource): Record<string, unknown> {
  const properties: Record<string, unknown> = {};
  const required: string[] = [];

  for (const field of action.fields) {
    properties[field.name] = fieldSchema(field);

    if (field.kind !== "nullable_string") {
      required.push(field.name);
    }
  }

  return { type: "object", additionalProperties: false, required, properties };
}

function fieldSchema(field: ActionFieldSource): Record<string, unknown> {
  switch (field.kind) {
    case "required_string":
      return {
        type: "string",
        pattern: field.pattern,
        maxLength: field.maximumLength,
      };
    case "nullable_string":
      return { type: ["string", "null"], maxLength: field.maximumLength };
    case "enum":
      return { type: "string", enum: [...field.values] };
    case "boolean":
      return { type: "boolean" };
    default:
      return assertNever(field, "Unexpected action source");
  }
}


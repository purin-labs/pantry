function renderActionDefinition(action: ActionSource): string {
  const constant = actionConstantPrefix(action);
  const definition = JSON.stringify(
    {
      provider: action.provider,
      verb: action.verb,
      method: action.method,
      pathPattern: action.path,
      stakes: action.stakes,
      argsSchema: buildJsonSchema(action),
      resourceKey: action.resourceKey,
      idempotency: action.idempotency,
      credentialScope: action.credentialScope,
      auditFields: action.auditFields,
    },
    null,
    2,
  );
  return (
    `export const ${constant}_TOOL = ${JSON.stringify(action.command)};\n\n` +
    `export const ${constant}_DEF = ${definition} as const satisfies ActionDef;`
  );
}

function actionConstantPrefix(action: ActionSource): string {
  switch (action.id) {
    case "stripe_charge_create":
      return "STRIPE_CHARGE_CREATE";
    case "stripe_refund_create":
      return "STRIPE_REFUND_CREATE";
    case "stripe_subscription_cancel":
      return "STRIPE_SUBSCRIPTION_CANCEL";
    case "stripe_payout_create":
      return "STRIPE_PAYOUT_CREATE";
    case "stripe_transfer_create":
      return "STRIPE_TRANSFER_CREATE";
    case "stripe_payment_intent_capture":
      return "STRIPE_PAYMENT_INTENT_CAPTURE";
    case "stripe_payment_intent_confirm":
      return "STRIPE_PAYMENT_INTENT_CONFIRM";
    case "stripe_subscription_update":
      return "STRIPE_SUBSCRIPTION_UPDATE";
    case "shopify_order_cancel":
      return "SHOPIFY_ORDER_CANCEL";
    default:
      return assertNever(action, "Unexpected action source");
  }
}


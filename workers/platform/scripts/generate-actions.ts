import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  ACTION_REGISTRY,
  type ActionFieldSource,
  type ActionSource,
} from "../action-registry/registry.ts";
import { assertNever } from "@purin-labs/std";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const EDGE_DIR = resolve(SCRIPT_DIR, "..");
// The action ledger of foundation/authority owns the registry; a Shopify file
// of areas/integrations reads it by the package name.
const GENERATED_TS = resolve(
  EDGE_DIR,
  "../../foundation/authority/generated/action-registry.ts",
);
async function main(): Promise<void> {
  validateRegistry(ACTION_REGISTRY);
  const content = renderTypeScript(ACTION_REGISTRY);

  if (process.argv.includes("--check")) {
    await assertGeneratedFile(GENERATED_TS, content);
  } else {
    await mkdir(dirname(GENERATED_TS), { recursive: true });
    await writeFile(GENERATED_TS, content, "utf8");
  }
}

function validateRegistry(actions: readonly ActionSource[]): void {
  const ids = new Set<string>();
  const commands = new Set<string>();
  const verbs = new Set<string>();
  const capabilities = new Set<string>();

  for (const action of actions) {
    if (
      ids.has(action.id) ||
      commands.has(action.command) ||
      verbs.has(action.verb) ||
      capabilities.has(action.capabilityId)
    ) {
      throw new Error(`Action registry identity is duplicated: ${action.id}`);
    }
    if (action.capabilityId !== `${action.provider}.${action.verb}`) {
      throw new Error(
        `Action registry capability does not match its executable verb: ${action.id}`,
      );
    }

    ids.add(action.id);
    commands.add(action.command);
    verbs.add(action.verb);
    capabilities.add(action.capabilityId);
  }

  const expected = [
    "stripe_charge_create",
    "stripe_refund_create",
    "stripe_subscription_cancel",
    "stripe_payout_create",
    "stripe_transfer_create",
    "stripe_payment_intent_capture",
    "stripe_payment_intent_confirm",
    "stripe_subscription_update",
    "shopify_order_cancel",
  ];

  if (actions.length !== expected.length) {
    throw new Error("Action registry baseline is incomplete");
  }

  for (const id of expected) {
    if (!ids.has(id)) {
      throw new Error(`Action registry is missing ${id}`);
    }
  }
}

async function assertGeneratedFile(
  path: string,
  expected: string,
): Promise<void> {
  let actual: string;

  try {
    actual = await readFile(path, "utf8");
  } catch {
    throw new Error(`Generated action artifact is missing: ${path}`);
  }

  if (actual !== expected) {
    throw new Error(`Generated action artifact is stale: ${path}`);
  }
}


#!/usr/bin/env node
// Prints SQL that adds a disabled policy row for every capability of the
// catalogue that an Organisation lacks. Rows that exist stay unchanged, so
// the SQL is safe to repeat.
//
// The Access read fails for an Organisation that lacks the policy row of any
// catalogue capability (`access_control_read_unavailable`). A new Organisation
// gets every row at activation. An Organisation that exists when a capability
// is added to the catalogue needs this SQL on its regional database, before
// or with the release that adds the capability.
//
//   node scripts/capability-policy-backfill-sql.mjs > backfill.sql
//   pnpm --filter @seams/platform exec wrangler d1 execute <binding> --env <env> --file backfill.sql
import { catalogueValues } from "./capability-policy-rows.mjs";

const MIGRATION_ID = "capability-policy-catalogue-backfill";
const provenance = `json_object('kind', 'cutover_disabled', 'migrationId', '${MIGRATION_ID}')`;
console.log(`-- Generated by scripts/capability-policy-backfill-sql.mjs
INSERT INTO organisation_capability_policy (
  organisation_id, capability_id, capability_version, mode,
  provenance_json, revision, changed_at
)
SELECT o.organisation_id, c.capability_id, c.capability_version, 'disabled',
  ${provenance}, 1, unixepoch() * 1000
FROM organisation o
CROSS JOIN (
  SELECT column1 AS capability_id, column2 AS capability_version FROM (VALUES
${catalogueValues()}
  )
) AS c
-- A purged Organisation has no policy rows: the purge erased them.
WHERE o.status <> 'purged'
ON CONFLICT (organisation_id, capability_id, capability_version) DO NOTHING;`);

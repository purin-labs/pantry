import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { gzipSync } from "node:zlib";
import { readVaultOnePasswordEnvironment } from "./worker-environment.mjs";
import {
  checkAndDeploy,
  isUploadedModule,
  platformDirectory as directory,
} from "./lib/side-worker.mjs";

// The 1Password store Worker runs the 1Password SDK for the Vault (Plan 79).
// The platform Worker binds it by name, so this Worker deploys first.
//
// `prepare` writes the SDK loader that the Worker profile aliases. The SDK
// core is generated by wasm-bindgen for Node: it reads its Wasm file with
// `fs` and compiles it from bytes, which a Worker cannot do. The prepared
// loader is the same file with that one step replaced by the module that the
// Worker imports. A new SDK version that changes the step fails here.

// The SDK core compresses to about 4.2 MB; the Worker plan allows 10 MB.
const MAXIMUM_COMPRESSED_BYTES = 6 * 1024 * 1024;

const NODE_LOADER = `const path = require('path').join(__dirname, 'core_bg.wasm');
const bytes = require('fs').readFileSync(path);

const wasmModule = new WebAssembly.Module(bytes);`;
const WORKER_LOADER = `// Prepared for the Worker: the Worker imports the compiled module.
const wasmModule = globalThis.__opSdkWasm;`;
const NODE_TEXT_CODING =
  "const { TextDecoder, TextEncoder } = require(`util`);";

const [operation, environment = "production", ...extra] = process.argv.slice(2);
if (operation !== "prepare" && operation !== "check" && operation !== "deploy")
  throw new Error("Select prepare, check or deploy");
if (extra.length > 0)
  throw new Error("Options are forbidden; edit the named Wrangler profile");

prepareLoader();
if (operation === "prepare") process.exit(0);

const config = readVaultOnePasswordEnvironment(environment);
console.log(`${operation}: ${config.name} (${environment})`);

checkAndDeploy({
  operation,
  environment,
  profile: "wrangler.vault-onepassword.jsonc",
  prefix: "satyr-vault-onepassword-",
  check: requireBoundedScript,
});

function prepareLoader() {
  const require = createRequire(join(directory, "package.json"));
  // The SDK's main file is dist/sdk.js; its core is a dependency of the SDK.
  const sdk = dirname(dirname(require.resolve("@1password/sdk")));
  const core = dirname(
    createRequire(join(sdk, "package.json")).resolve("@1password/sdk-core"),
  );
  const source = readFileSync(join(core, "core.js"), "utf8");
  if (!source.includes(NODE_LOADER) || !source.includes(NODE_TEXT_CODING))
    throw new Error(
      "vault-onepassword: the SDK core loader changed; review the prepared loader",
    );
  const output = join(directory, ".generated/vault-onepassword");
  mkdirSync(output, { recursive: true });
  writeFileSync(
    join(output, "core.cjs"),
    source.replace(NODE_LOADER, WORKER_LOADER).replace(NODE_TEXT_CODING, ""),
  );
  copyFileSync(join(core, "core_bg.wasm"), join(output, "core_bg.wasm"));
  console.log(`prepare: SDK loader written to ${output}`);
}

function requireBoundedScript(bundle) {
  const modules = readdirSync(bundle).filter(isUploadedModule);
  const wasm = modules.filter((name) => name.endsWith(".wasm"));
  if (wasm.length !== 1)
    throw new Error(
      `vault-onepassword: expected the SDK core as the one Wasm module, found ${wasm.length}; an import brought platform code into the script`,
    );
  const compressed = modules.reduce(
    (total, name) => total + gzipSync(readFileSync(join(bundle, name))).length,
    0,
  );
  if (compressed > MAXIMUM_COMPRESSED_BYTES)
    throw new Error(
      `vault-onepassword: the script is ${compressed} compressed bytes; the limit is ${MAXIMUM_COMPRESSED_BYTES}`,
    );
  const bytes = modules.reduce(
    (total, name) => total + statSync(join(bundle, name)).size,
    0,
  );
  console.log(
    `check: script is ${bytes} bytes (${compressed} compressed) in ${modules.length} module(s)`,
  );
}

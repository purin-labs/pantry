import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

export const UNICODE_VERSION = "17.0.0";
const cache = new URL("../generated/unicode/", import.meta.url);
const output = new URL("../src/unicode-tables.ts", import.meta.url);
const sources = {
  "UnicodeData.txt":
    "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  "CaseFolding.txt":
    "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183",
  "DerivedNormalizationProps.txt":
    "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
  "DerivedCoreProperties.txt":
    "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
  "NormalizationTest.txt":
    "5019ffd530751a741900c849c0e010332f142a3612234639bd200b82138a87db",
};

export async function readUnicodeSource(name) {
  const expected = sources[name];
  if (expected === undefined)
    throw new Error(`Unknown Unicode source: ${name}`);
  const path = new URL(name, cache);
  let bytes;
  try {
    bytes = await readFile(path);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    const response = await fetch(
      `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/${name}`,
    );
    if (!response.ok)
      throw new Error(`Unicode download failed: ${name}: ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    await mkdir(cache, { recursive: true });
    await writeFile(path, bytes);
  }
  if (createHash("sha256").update(bytes).digest("hex") !== expected) {
    throw new Error(`Unicode source digest differs: ${name}`);
  }
  return bytes.toString("utf8");
}

function codePoints(value) {
  return value.trim().split(/\s+/u).map(parseCodePoint);
}

function parseCodePoint(value) {
  return Number.parseInt(value, 16);
}

function propertyRanges(text, property) {
  const ranges = [];
  for (const line of text.split("\n")) {
    const [range, name] = line.split("#")[0].split(";").map(trim);
    if (name !== property) continue;
    const [first, last = first] = range.split("..").map(parseCodePoint);
    ranges.push([first, last]);
  }
  return ranges;
}

function trim(value) {
  return value.trim();
}

function inRanges(codePoint, ranges) {
  return ranges.some(rangeContains.bind(null, codePoint));
}

function rangeContains(codePoint, [first, last]) {
  return codePoint >= first && codePoint <= last;
}

function table(name, entries, type) {
  return `export const ${name}: ${type} = ${JSON.stringify(entries)};\n`;
}

async function generate() {
  const unicodeData = await readUnicodeSource("UnicodeData.txt");
  const exclusions = propertyRanges(
    await readUnicodeSource("DerivedNormalizationProps.txt"),
    "Full_Composition_Exclusion",
  );
  const ignorables = propertyRanges(
    await readUnicodeSource("DerivedCoreProperties.txt"),
    "Default_Ignorable_Code_Point",
  );
  const decompositions = {};
  const combiningClasses = {};
  const compositions = {};
  const caseFolds = {};
  for (const line of unicodeData.split("\n")) {
    if (line.length === 0) continue;
    const fields = line.split(";");
    const codePoint = parseCodePoint(fields[0]);
    const combiningClass = Number(fields[3]);
    if (combiningClass !== 0) combiningClasses[codePoint] = combiningClass;
    const decomposition = fields[5];
    if (decomposition.length === 0) continue;
    const parts = codePoints(decomposition.replace(/^<[^>]+>\s*/u, ""));
    decompositions[codePoint] = parts;
    if (
      !decomposition.startsWith("<") &&
      parts.length === 2 &&
      !inRanges(codePoint, exclusions)
    ) {
      compositions[`${parts[0]},${parts[1]}`] = codePoint;
    }
  }
  for (const line of (await readUnicodeSource("CaseFolding.txt")).split("\n")) {
    const [raw, status, mapping] = line.split("#")[0].split(";").map(trim);
    if (status === "C" || status === "F")
      caseFolds[parseCodePoint(raw)] = codePoints(mapping);
  }
  const source =
    "// Generated by scripts/generate-unicode.mjs. Do not edit.\n" +
    "// Unicode 17.0.0 data. See ../UNICODE-LICENSE.txt.\n" +
    `export const COMMERCE_UNICODE_VERSION = "${UNICODE_VERSION}";\n` +
    table(
      "DECOMPOSITIONS",
      decompositions,
      "Readonly<Record<number, readonly number[]>>",
    ) +
    table(
      "COMBINING_CLASSES",
      combiningClasses,
      "Readonly<Record<number, number>>",
    ) +
    table("COMPOSITIONS", compositions, "Readonly<Record<string, number>>") +
    table(
      "CASE_FOLDS",
      caseFolds,
      "Readonly<Record<number, readonly number[]>>",
    ) +
    table(
      "DEFAULT_IGNORABLE_RANGES",
      ignorables,
      "readonly (readonly [number, number])[]",
    );
  const text = await format(source, { parser: "typescript" });
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")) !== text)
      throw new Error("Unicode tables are stale");
  } else {
    await writeFile(output, text);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await generate();
